#!/usr/bin/env python3
"""Compiles the drum kits in kits/*/ into lib/irdsp/src/DrumKitData.cpp.

Each kit folder has a kit.txt (see kits/rock/kit.txt) and its 16-bit mono
WAVs. The output holds the samples as int16 arrays and the kit table, all in
flash on the Teensy (IRDSP_PROGMEM). Kit 0 is always the synthesized kit.

The file is generated by every build (a PlatformIO pre-script and the host
Makefile) and only rewritten when a kit changed. Python standard library only.

  python3 tools/make_kits.py [--force]
"""
import os
import sys
import wave

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KITS = os.path.join(ROOT, "kits")
OUT = os.path.join(ROOT, "lib", "irdsp", "src", "DrumKitData.cpp")

# Lane names in kit.txt, in DrumVoice order (DrumMachine.h). The click has no
# samples: it is always synthesized.
LANES = ["kick", "snare", "rim", "hatc", "hato", "ride", "click", "crash", "tomh", "toml"]
# A sample's velocity: 1..9, or g/x/X for 3/6/9.
LEVELS = dict({"g": 3, "x": 6, "X": 9}, **{str(v): v for v in range(1, 10)})
MAX_PER_LANE = 4
FS = 44100


def read_kit(folder):
    """Parses kit.txt: returns (settings dict, list of sample dicts)."""
    kit = {"name": os.path.basename(folder), "title": os.path.basename(folder), "dir": folder}
    samples = []
    path = os.path.join(folder, "kit.txt")
    with open(path) as f:
        for n, line in enumerate(f, 1):
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            words = line.split()
            if words[0] in ("name", "title", "source", "order"):
                kit[words[0]] = line.split(None, 1)[1]
                continue
            if len(words) != 7 or words[0] not in LANES or words[0] == "click" or words[1] not in LEVELS:
                sys.exit("%s:%d: expected: lane level file source max fade peak" % (path, n))
            samples.append({"lane": LANES.index(words[0]), "vel": LEVELS[words[1]], "file": words[2],
                            "source": words[3], "max": float(words[4]), "fade": float(words[5]),
                            "peak": None if words[6] == "-" else float(words[6])})
    if len(kit["name"]) > 9 or len(kit["title"]) > 13:
        sys.exit("%s: name is at most 9 characters, title at most 13" % path)
    for lane in range(len(LANES)):
        if sum(s["lane"] == lane for s in samples) > MAX_PER_LANE:
            sys.exit("%s: at most %d samples per lane" % (path, MAX_PER_LANE))
    return kit, samples


def kit_folders():
    """The kit folders by their `order` (kit numbers are saved in settings,
    so a new kit goes last), then by name."""
    if not os.path.isdir(KITS):
        return []
    folders = [os.path.join(KITS, d) for d in os.listdir(KITS)
               if os.path.isfile(os.path.join(KITS, d, "kit.txt"))]
    return sorted(folders, key=lambda f: (int(read_kit(f)[0].get("order", 999)), f))


def read_wav(path):
    with wave.open(path) as w:
        if w.getnchannels() != 1 or w.getsampwidth() != 2 or w.getframerate() != FS:
            sys.exit("%s: must be 16-bit mono %d Hz (tools/import_kit.py makes them)" % (path, FS))
        data = w.readframes(w.getnframes())
    return [int.from_bytes(data[i:i + 2], "little", signed=True) for i in range(0, len(data), 2)]


def generate():
    out = ["// Generated by tools/make_kits.py from kits/*/ - do not edit.",
           '#include "DrumKit.h"', '#include "irdsp_port.h"', "", "namespace irdsp {", "",
           "namespace {", ""]
    tables = []
    total = 0
    for folder in kit_folders():
        kit, samples = read_kit(folder)
        ident = "".join(c for c in kit["name"].title() if c.isalnum())
        samples.sort(key=lambda s: (s["lane"], s["vel"]))
        first = [0] * len(LANES)
        count = [0] * len(LANES)
        entries = []
        for i, s in enumerate(samples):
            if count[s["lane"]] == 0:
                first[s["lane"]] = i
            count[s["lane"]] += 1
            pcm = read_wav(os.path.join(folder, s["file"]))
            total += len(pcm)
            name = "k%sSample%d" % (ident, i)
            out.append("// %s/%s" % (os.path.basename(folder), s["file"]))
            out.append("IRDSP_PROGMEM const int16_t %s[] = {" % name)
            for j in range(0, len(pcm), 16):
                out.append("    " + ",".join(str(v) for v in pcm[j:j + 16]) + ",")
            out.append("};")
            entries.append("{%s, %d, %d}" % (name, len(pcm), s["vel"]))
        out.append("IRDSP_PROGMEM const DrumSample k%sSamples[] = {%s};" % (ident, ", ".join(entries)))
        out.append("")
        tables.append('{"%s", "%s", {%s}, {%s}, k%sSamples}' % (
            kit["name"], kit["title"], ", ".join(map(str, first)), ", ".join(map(str, count)), ident))
    lanes = ", ".join(["0"] * len(LANES))
    out.append("IRDSP_PROGMEM const DrumKit kKits[] = {")
    out.append('    {"synth", "synth", {%s}, {%s}, nullptr},' % (lanes, lanes))
    for t in tables:
        out.append("    %s," % t)
    out += ["};", "", "}  // namespace", "",
            "IRDSP_COLD int drumKitCount() { return (int)(sizeof(kKits) / sizeof(kKits[0])); }", "",
            "IRDSP_COLD const DrumKit& drumKit(int i) { return kKits[i < 0 || i >= drumKitCount() ? 0 : i]; }",
            "", "}  // namespace irdsp", ""]
    generate.kb = total * 2 / 1024
    return "\n".join(out)


def up_to_date():
    if not os.path.exists(OUT):
        return False
    t = os.path.getmtime(OUT)
    inputs = [__file__]
    for folder in kit_folders():
        inputs += [os.path.join(folder, f) for f in os.listdir(folder)]
    return all(os.path.getmtime(p) <= t for p in inputs)


def main():
    if "--force" not in sys.argv and up_to_date():
        return
    text = generate()
    with open(OUT, "w") as f:
        f.write(text)
    print("make_kits: wrote %s (%d kits, %.0f KB of samples)" % (os.path.relpath(OUT, ROOT), len(kit_folders()) + 1,
                                                                generate.kb))


if __name__ == "__main__":
    main()
