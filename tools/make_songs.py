#!/usr/bin/env python3
"""Compiles the built-in drum songs in songs/*.txt into
lib/irdsp/src/DrumSongData.cpp (the DrumSong format of DrumSong.h, in flash
on the Teensy).

Song file format (see songs/README.md):

  name   sandman            # command name, at most 15 characters
  title  Sandman-ish        # display name, at most 23 characters
  bpm    123
  meter  4/4                # default meter of the bars below
  grid   4                  # default steps per quarter note (4 = 16ths,
                            # 3 = 8th triplets, 6 = 16th triplets, 8 = 32nds)
  bar V                     # a bar, optionally: meter 3/4  grid 6
    kick   9.......8.......  # one lane per line: . rest, 1..9 velocity
    snare  ....9.......9...  # (g x X = 3 6 9); beats x grid x 4/unit steps
    bass   E1 - E1 - G1 - . . A1:9 - - - x - E1 -   # one token per step
  bar V2 like V             # V's drums (and meter, grid), its own bass
    bass   C2 - C2 - ...
  song   V*3 F  V*3 F       # the bars in order; ID*n repeats

Bass tokens: a note (E1, F#1, Bb0; C-based octaves, E1 = MIDI 28; B0..G3),
optionally :velocity (1..9, default 7); - holds the note; . mutes it; x is a
dead note on the last pitch (optionally x:velocity). A note rings until the
next token that isn't -.

Generated by every build (a PlatformIO pre-script and the host Makefile) and
only rewritten when a song changed. Python standard library only.

  python3 tools/make_songs.py [--force]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_kits import LANES  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SONGS = os.path.join(ROOT, "songs")
OUT = os.path.join(ROOT, "lib", "irdsp", "src", "DrumSongData.cpp")
PPQ = 24  # kSongPpq
BASS_MIN, BASS_MAX, BASS_VEL = 23, 55, 7  # PluckBass::kMinNote, kMaxNote; default velocity
BASS_MAX_TICK = (1 << 20) - 1             # kBassMaxTick
PITCH = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}
VEL = dict({".": 0, "g": 3, "x": 6, "X": 9}, **{str(v): v for v in range(1, 10)})


def fail(path, n, msg):
    sys.exit("%s:%d: %s" % (path, n, msg))


def parse_meter(path, n, text):
    try:
        a, b = text.split("/")
        beats, unit = int(a), int(b)
    except ValueError:
        fail(path, n, "meter must look like 4/4")
    if beats < 1 or beats > 16 or unit not in (2, 4, 8, 16):
        fail(path, n, "unsupported meter %s" % text)
    return beats, unit


def read_song(path):
    song = {"name": os.path.splitext(os.path.basename(path))[0], "title": None, "bpm": 120,
            "meter": (4, 4), "grid": 4, "bars": {}, "order": []}
    cur = None
    with open(path) as f:
        for n, raw in enumerate(f, 1):
            # A comment starts with # at the line's start or after a space,
            # so sharps (C#2) are notes.
            line = re.split(r"(?:^|\s)#", raw, maxsplit=1)[0].rstrip()
            if not line.strip():
                continue
            words = line.split()
            key = words[0]
            if raw[0] in " \t" and cur is not None and key == "bass":
                cur["bass"] = (n, words[1:])
                continue
            if raw[0] in " \t" and cur is not None and key in LANES:
                if len(words) != 2:
                    fail(path, n, "expected: lane steps")
                cur["lanes"][LANES.index(key)] = (n, words[1])
                continue
            cur = None
            if key in ("name", "title"):
                song[key] = line.split(None, 1)[1].strip()
            elif key == "bpm":
                song["bpm"] = int(words[1])
            elif key == "meter":
                song["meter"] = parse_meter(path, n, words[1])
            elif key == "grid":
                song["grid"] = int(words[1])
            elif key == "bar":
                if len(words) < 2:
                    fail(path, n, "bar needs an ID")
                bar = {"meter": song["meter"], "grid": song["grid"], "lanes": {}, "line": n, "bass": None}
                rest = words[2:]
                while rest:
                    if rest[0] == "like" and len(rest) > 1:
                        if rest[1] not in song["bars"]:
                            fail(path, n, "like %s: no such bar above" % rest[1])
                        src = song["bars"][rest[1]]
                        bar["meter"], bar["grid"], bar["lanes"] = src["meter"], src["grid"], dict(src["lanes"])
                    elif rest[0] == "meter" and len(rest) > 1:
                        bar["meter"] = parse_meter(path, n, rest[1])
                    elif rest[0] == "grid" and len(rest) > 1:
                        bar["grid"] = int(rest[1])
                    else:
                        fail(path, n, "unknown bar option %s" % rest[0])
                    rest = rest[2:]
                song["bars"][words[1]] = bar
                cur = bar
            elif key == "song":
                for w in words[1:]:
                    bid, _, times = w.partition("*")
                    song["order"] += [(n, bid)] * (int(times) if times else 1)
            else:
                fail(path, n, "unknown keyword %s (lane lines must be indented)" % key)
    if not song["title"]:
        song["title"] = song["name"]
    if len(song["name"]) > 15 or len(song["title"]) > 23:
        sys.exit("%s: name is at most 15 characters, title at most 23" % path)
    if not song["order"]:
        sys.exit("%s: no 'song' line" % path)
    return song


def parse_bass_token(path, n, tok, last):
    """Returns (note, vel, dead) for a note or x (last: the previous pitch)."""
    head, _, v = tok.partition(":")
    vel = BASS_VEL
    if v:
        if v not in "123456789" or len(v) != 1:
            fail(path, n, "bad velocity in %r (1..9)" % tok)
        vel = int(v)
    if head == "x":
        if last is None:
            fail(path, n, "x (dead note) before any note")
        return last, vel, True
    if not head or head[0].upper() not in PITCH:
        fail(path, n, "bad bass token %r (a note like E1, F#1, Bb0; - . or x)" % tok)
    pc = PITCH[head[0].upper()]
    rest = head[1:]
    if rest[:1] == "#":
        pc, rest = pc + 1, rest[1:]
    elif rest[:1] == "b":
        pc, rest = pc - 1, rest[1:]
    try:
        octave = int(rest)
    except ValueError:
        fail(path, n, "bad bass note %r" % tok)
    note = 12 * (octave + 1) + pc
    if not BASS_MIN <= note <= BASS_MAX:
        fail(path, n, "bass note %r out of range (B0..G3)" % tok)
    return note, vel, False


def compile_song(path, song):
    """Returns (events, bars, end tick, bass): events (tick, lane, vel)
    sorted, bars (tick, firstEvent, beats, unit, firstBass), bass (tick,
    note, vel, dead) sorted, note 0 = mute."""
    events, bars, bass = [], [], []
    tick = 0
    last, sounding = None, False  # the bass's last pitch; a note ringing
    for n, bid in song["order"]:
        if bid not in song["bars"]:
            fail(path, n, "no bar %s" % bid)
        bar = song["bars"][bid]
        beats, unit = bar["meter"]
        grid = bar["grid"]
        if PPQ % grid:
            fail(path, bar["line"], "grid must divide %d" % PPQ)
        steps = beats * grid * 4 // unit
        step_ticks = PPQ // grid
        bar_events = []
        for lane, (ln, text) in bar["lanes"].items():
            if len(text) != steps:
                fail(path, ln, "%d steps, want %d (%d/%d at grid %d)" % (len(text), steps, beats, unit, grid))
            for i, c in enumerate(text):
                if c not in VEL:
                    fail(path, ln, "bad step %r" % c)
                if VEL[c]:
                    bar_events.append((tick + i * step_ticks, lane, VEL[c]))
        bars.append((tick, len(events), beats, unit, len(bass)))
        events += sorted(bar_events)
        if bar["bass"]:
            ln, toks = bar["bass"]
            if len(toks) != steps:
                fail(path, ln, "bass: %d tokens, want %d (%d/%d at grid %d)" % (len(toks), steps, beats, unit, grid))
            for i, tok in enumerate(toks):
                t = tick + i * step_ticks
                if tok == "-":
                    continue
                if tok == ".":
                    if sounding:
                        bass.append((t, 0, 0, False))
                    sounding = False
                    continue
                note, vel, dead = parse_bass_token(path, ln, tok, last)
                bass.append((t, note, vel, dead))
                last, sounding = note, not dead
        elif sounding:
            # A bar without a bass line is silent: the note stops at its start.
            bass.append((tick, 0, 0, False))
            sounding = False
        tick += beats * PPQ * 4 // unit
    if tick > BASS_MAX_TICK and bass:
        sys.exit("%s: too long for the bass line's ticks" % path)
    return events, bars, tick, bass


def song_files():
    if not os.path.isdir(SONGS):
        return []
    return sorted(os.path.join(SONGS, f) for f in os.listdir(SONGS) if f.endswith(".txt"))


def generate():
    out = ["// Generated by tools/make_songs.py from songs/*.txt - do not edit.",
           '#include "DrumSong.h"', '#include "irdsp_port.h"', "", "namespace irdsp {", "", "namespace {", ""]
    table = []
    for k, path in enumerate(song_files()):
        song = read_song(path)
        events, bars, end, bass = compile_song(path, song)
        out.append("// %s" % os.path.relpath(path, ROOT))
        # Packed as in DrumSong.h: tick << 8 | lane << 4 | velocity.
        out.append("IRDSP_PROGMEM const SongEvent kSong%dEvents[] = {" % k)
        for i in range(0, len(events), 8):
            out.append("    " + " ".join("{0x%x}," % (t << 8 | l << 4 | v) for t, l, v in events[i:i + 8]))
        if not events:
            out.append("    {0},")
        out.append("};")
        out.append("IRDSP_PROGMEM const SongBar kSong%dBars[] = {" % k)
        for i in range(0, len(bars), 6):
            out.append("    " + " ".join("{%d, %d, %d, %d, %d}," % b for b in bars[i:i + 6]))
        out.append("};")
        # Packed as in DrumSong.h: tick << 12 | note << 5 | velocity << 1 | dead.
        out.append("IRDSP_PROGMEM const BassEvent kSong%dBass[] = {" % k)
        for i in range(0, len(bass), 8):
            out.append("    " + " ".join("{0x%x}," % (t << 12 | n << 5 | v << 1 | int(d)) for t, n, v, d in bass[i:i + 8]))
        if not bass:
            out.append("    {0},")
        out.append("};")
        out.append("")
        table.append('{"%s", "%s", %d, kSong%dEvents, %d, kSong%dBars, %d, %d, %s, %d}' % (
            song["name"], song["title"].replace('"', '\\"'), song["bpm"], k, len(events), k, len(bars), end,
            "kSong%dBass" % k if bass else "nullptr", len(bass)))
    if table:
        out.append("IRDSP_PROGMEM const DrumSong kSongs[] = {")
        out += ["    %s," % t for t in table]
        out += ["};", "constexpr int kSongCount = (int)(sizeof(kSongs) / sizeof(kSongs[0]));"]
    else:
        out += ["IRDSP_PROGMEM const DrumSong kSongs[1] = {};", "constexpr int kSongCount = 0;"]
    out += ["", "}  // namespace", "",
            "IRDSP_COLD int drumSongCount() { return kSongCount; }", "",
            "IRDSP_COLD const DrumSong& drumSong(int i) { return kSongs[i < 0 || i >= kSongCount ? 0 : i]; }",
            "", "}  // namespace irdsp", ""]
    return "\n".join(out), len(table)


def up_to_date():
    if not os.path.exists(OUT):
        return False
    t = os.path.getmtime(OUT)
    inputs = [__file__, os.path.join(os.path.dirname(__file__), "make_kits.py")] + song_files()
    return all(os.path.getmtime(p) <= t for p in inputs)


def main():
    if "--force" not in sys.argv and up_to_date():
        return
    text, count = generate()
    with open(OUT, "w") as f:
        f.write(text)
    print("make_songs: wrote %s (%d songs)" % (os.path.relpath(OUT, ROOT), count))


if __name__ == "__main__":
    main()
