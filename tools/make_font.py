#!/usr/bin/env python3
"""Converts the panel's BDF fonts (fonts/) into lib/oledui/src/Fonts.cpp.

Each glyph (ASCII 32..126) is stored in the SSD1306 page layout: for each
8-pixel page from the top, one byte per column, bit 0 = top pixel. An 8x16
glyph is 2 pages x 8 columns = 16 bytes, a 16x32 glyph 4 x 16 = 64 bytes.

    python3 -I tools/make_font.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = [  # (C name, BDF file)
    ("kFont8x16", "fonts/spleen/spleen-8x16.bdf"),
    ("kFont16x32", "fonts/spleen/spleen-16x32.bdf"),
]
OUT = os.path.join(ROOT, "lib/oledui/src/Fonts.cpp")
FIRST, LAST = 32, 126


def parse(path):
    """Returns (width, height, {code: rows}), rows = list of ints, MSB = left."""
    w = h = ox = oy = None
    glyphs, code, bbx, rows = {}, None, None, None
    with open(path, encoding="ascii", errors="replace") as f:
        for line in f:
            words = line.split()
            if not words:
                continue
            key = words[0]
            if key == "FONTBOUNDINGBOX":
                w, h, ox, oy = map(int, words[1:5])
            elif key == "ENCODING":
                code = int(words[1])
            elif key == "BBX":
                bbx = list(map(int, words[1:5]))
            elif key == "BITMAP":
                rows = []
            elif key == "ENDCHAR":
                if code is not None and FIRST <= code <= LAST:
                    glyphs[code] = place(rows, bbx, w, h, ox, oy)
                code, bbx, rows = None, None, None
            elif rows is not None:
                rows.append(int(key, 16))
    if None in (w, h):
        sys.exit("%s: no FONTBOUNDINGBOX" % path)
    missing = [c for c in range(FIRST, LAST + 1) if c not in glyphs]
    if missing:
        sys.exit("%s: missing glyphs %s" % (path, missing))
    return w, h, glyphs


def place(rows, bbx, w, h, ox, oy):
    """The glyph's bitmap placed in the font's w x h cell (list of h ints)."""
    gw, gh, gx, gy = bbx
    bits = ((gw + 7) // 8) * 8
    cell = [0] * h
    top = (h + oy) - (gh + gy)  # rows from the cell top to the glyph's top
    for i, r in enumerate(rows[:gh]):
        y = top + i
        if 0 <= y < h:
            # Left-align the glyph's bits in a w-bit row, shifted by its x offset.
            v = r >> (bits - gw)
            shift = w - gw - (gx - ox)
            cell[y] = (v << shift) if shift >= 0 else (v >> -shift)
            cell[y] &= (1 << w) - 1
    return cell


def to_pages(cell, w, h):
    out = []
    for p in range(h // 8):
        for x in range(w):
            b = 0
            for bit in range(8):
                if cell[p * 8 + bit] & (1 << (w - 1 - x)):
                    b |= 1 << bit
            out.append(b)
    return out


def main():
    with open(os.path.join(ROOT, "fonts/spleen/LICENSE"), encoding="utf-8") as f:
        license_text = f.read().strip()
    lines = [
        "// Fonts.cpp - GENERATED by tools/make_font.py from fonts/spleen/*.bdf; do not edit.",
        "//",
        "// Spleen fonts by Frederic Cambus (https://github.com/fcambus/spleen), 2.2.0:",
        "//",
    ]
    lines += ["// " + l if l else "//" for l in license_text.splitlines()]
    lines += ["", '#include "Fonts.h"', "", '#include "ui_port.h"', "", "namespace ui {", ""]
    for name, rel in FONTS:
        w, h, glyphs = parse(os.path.join(ROOT, rel))
        n = w * h // 8
        lines.append("// %dx%d, ASCII %d..%d, %d bytes per glyph." % (w, h, FIRST, LAST, n))
        lines.append("const uint8_t UI_PROGMEM %s[%d][%d] = {" % (name, LAST - FIRST + 1, n))
        for c in range(FIRST, LAST + 1):
            data = to_pages(glyphs[c], w, h)
            ch = chr(c)
            label = "'\\\\'" if ch == "\\" else "'%s'" % ch
            lines.append("    {%s},  // %s" % (", ".join("0x%02x" % b for b in data), label))
        lines.append("};")
        lines.append("")
    lines += ["}  // namespace ui", ""]
    with open(OUT, "w", encoding="ascii") as f:
        f.write("\n".join(lines))
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
